use bundlebase_common::BundlebaseError;
use pest::Parser;

/// Parse a command statement into a BundleCommand.
///
/// This is the main entry point for parsing command statements into BundleCommand that can be
/// executed on a BundleBuilder.
///
/// Most rules are handled by `parse_from_rule()` which is generated by the `register_commands!`
/// macro. Special cases (like fetch_stmt which maps to either Fetch or FetchAll) are handled
/// explicitly here.
///
/// # Arguments
///
/// * `command_str` - The command statement string to parse
///
/// # Returns
///
/// * `Ok(BundleCommand)` - Successfully parsed command
/// * `Err(BundlebaseError)` - Parsing failed or statement type not supported
///
/// # Examples
///
/// ```ignore
/// use bundlebase::bundle::{parse_command, BundleCommand};
///
/// // Parse a FILTER statement
/// let cmd = parse_command("FILTER WHERE country = 'USA'").unwrap();
///
/// // Parse a SELECT statement
/// let cmd = parse_command("SELECT name, email FROM bundle").unwrap();
///
/// // Parse an ATTACH statement
/// let cmd = parse_command("ATTACH 'data.parquet'").unwrap();
///
/// // Execute on a BundleBuilder
/// cmd.execute(&mut bundle).await?;
/// ```
pub fn parse_command(command_str: &str) -> Result<BundleCommand, BundlebaseError> {
    let mut pairs = BundlebaseParser::parse(Rule::statement, command_str)
        .map_err(|e| format_pest_error(e, command_str))?;

    // Get the top-level statement rule
    let statement = pairs
        .next()
        .ok_or_else(|| BundlebaseError::from("Parser produced empty result"))?;

    // Get the category rule (data_modification_stmt, schema_stmt, etc.)
    let category_stmt = statement
        .into_inner()
        .next()
        .ok_or_else(|| BundlebaseError::from("Parser produced empty inner statement"))?;

    // Get the actual statement type from the category
    let inner_stmt = category_stmt
        .into_inner()
        .next()
        .ok_or_else(|| BundlebaseError::from("Parser produced empty statement in category"))?;

    let rule = inner_stmt.as_rule();

    // Handle special cases first
    match rule {
        // FETCH is either FetchCommand or FetchAllCommand. Grammar:
        //   fetch_stmt = ^"fetch" ~ (^"all" ~ fetch_mode | identifier ~ fetch_mode) ~ ...
        // FETCH ALL has no `identifier` child; FETCH <pack> does. Disambiguate on
        // the parse structure, not substring text — a pack literally named
        // "install" or "wallets" contains "all" and must not become FETCH ALL. bb-8gq.
        Rule::fetch_stmt => {
            let has_pack_identifier = inner_stmt
                .clone()
                .into_inner()
                .any(|p| p.as_rule() == Rule::identifier);
            if has_pack_identifier {
                Ok(BundleCommand::Fetch(FetchCommand::from_statement(
                    inner_stmt,
                )?))
            } else {
                Ok(BundleCommand::FetchAll(FetchAllCommand::from_statement(
                    inner_stmt,
                )?))
            }
        }

        // All other rules use the centralized parse_from_rule() function
        _ => match parse_from_rule(rule, inner_stmt)? {
            Some(cmd) => Ok(cmd),
            None => Err("Unexpected statement type".into()),
        },
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_sql_empty() {
        let result = parse_command("");
        assert!(result.is_err());
        let err_msg = result.unwrap_err().to_string();
        assert!(err_msg.contains("Syntax error"));
    }

    #[test]
    fn test_fetch_pack_named_like_all_is_not_fetch_all() {
        // bb-8gq: a pack whose name contains "all" (e.g. "install") must parse as
        // FETCH <pack>, not FETCH ALL. Regression guard for substring dispatch.
        let cmd = parse_command("FETCH install ADD").expect("FETCH install ADD should parse");
        assert!(
            matches!(cmd, BundleCommand::Fetch(_)),
            "pack named 'install' should be a single-pack Fetch, not FetchAll"
        );

        let all = parse_command("FETCH ALL ADD").expect("FETCH ALL ADD should parse");
        assert!(matches!(all, BundleCommand::FetchAll(_)));
    }

    #[test]
    fn test_commit_message_with_backslash_parses() {
        // bb-8gq: auto-commit builds `COMMIT <escape_string(msg)>`. A message
        // ending in a backslash (or mixing backslashes and quotes) must not
        // escape the closing quote and break parsing.
        for msg in [
            "restore C:\\backup\\",
            "path C:\\net\\data",
            "weird ' and \\ together",
            "trailing \\",
        ] {
            let sql = format!("COMMIT {}", escape_string(msg));
            let cmd = parse_command(&sql).unwrap_or_else(|e| panic!("{sql} should parse: {e}"));
            assert!(
                matches!(cmd, BundleCommand::Commit(_)),
                "expected Commit for {sql}"
            );
        }
    }

    #[test]
    fn test_show_always_updates_is_facade_and_does_not_panic() {
        // bb-8gq: SHOW ALWAYS UPDATES is a read-only facade command; converting it
        // previously hit unreachable!() and panicked. Must return Ok.
        let cmd = parse_command("SHOW ALWAYS UPDATES").expect("SHOW ALWAYS UPDATES should parse");
        assert!(cmd.is_facade_command());
        assert!(cmd.into_facade_command().is_ok());
    }

    #[test]
    fn test_parse_create_view() {
        let cmd = parse_command("CREATE VIEW adults AS SELECT * FROM bundle WHERE age > 21");
        assert!(
            cmd.is_ok(),
            "CREATE VIEW should parse successfully: {:?}",
            cmd.err()
        );
        let cmd = cmd.unwrap();
        assert!(matches!(cmd, BundleCommand::CreateView(_)));
    }
}
